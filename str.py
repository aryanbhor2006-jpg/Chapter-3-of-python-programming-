#Slicing

name1 = "Aryan"
sl1 = name1[0:4]  #slicing name1 from 0 to 4
print(sl1)

name2 = "Santosh"
sl2 = name2[1:4]  #slicing name2 from 1 to 4
print(sl2)

name3 = "Python"
sl3 = name3[2:5]   #slicing name3 from 2 to 5
print(sl3)

#Negative slicing

name4 = "Aryan"
sl4= name4[-6:-3]  #slicing name from -6 to -3   
print(sl4)